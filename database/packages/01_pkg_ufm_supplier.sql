CREATE OR REPLACE PACKAGE PKG_UFM_SUPPLIER AS

    PROCEDURE GET_SUPPLIER_DETAILS(
        P_SUPPLIER_NO   IN SUPPLIER.SUPPLIER_NO%TYPE,
        P_SUPPLIER_NAME OUT SUPPLIER.SUPPLIER_NAME%TYPE
    );

    PROCEDURE GET_ALL_SUPPLIERS(
        P_SUPPLIERS OUT SYS_REFCURSOR
    );

END PKG_UFM_SUPPLIER;
/

CREATE OR REPLACE PACKAGE BODY PKG_UFM_SUPPLIER AS

    PROCEDURE GET_SUPPLIER_DETAILS(
        P_SUPPLIER_NO   IN SUPPLIER.SUPPLIER_NO%TYPE,
        P_SUPPLIER_NAME OUT SUPPLIER.SUPPLIER_NAME%TYPE
    )
    AS
    BEGIN
        SELECT SUPPLIER_NAME
        INTO P_SUPPLIER_NAME
        FROM SUPPLIER
        WHERE SUPPLIER_NO = P_SUPPLIER_NO;

    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            P_SUPPLIER_NAME := NULL;
    END GET_SUPPLIER_DETAILS;


    PROCEDURE GET_ALL_SUPPLIERS(
        P_SUPPLIERS OUT SYS_REFCURSOR
    )
    AS
    BEGIN
        OPEN P_SUPPLIERS FOR
            SELECT
                SUPPLIER_ID,
                SUPPLIER_NO,
                SUPPLIER_NAME,
                STATUS
            FROM SUPPLIER
            ORDER BY SUPPLIER_NO;
    END GET_ALL_SUPPLIERS;

END PKG_UFM_SUPPLIER;
